// Native children must not inherit another harness's tokens, session selectors,
// executable preload hooks or arbitrary application secrets. Config/session
// directories and the gateway token are added explicitly by each adapter.
const runtimeKeys = [
  "PATH",
  "HOME",
  "TMPDIR",
  "TMP",
  "TEMP",
  "LANG",
  "LC_ALL",
  "SSL_CERT_FILE",
  "SSL_CERT_DIR",
  "HTTPS_PROXY",
  "HTTP_PROXY",
  "NO_PROXY",
];
export function harnessEnvironment(providerKeys: readonly string[] = []) {
  const env: NodeJS.ProcessEnv = {};
  for (const key of runtimeKeys)
    if (process.env[key] !== undefined) env[key] = process.env[key];
  for (const key of providerKeys)
    if (process.env[key] !== undefined) env[key] = process.env[key];
  return env;
}

